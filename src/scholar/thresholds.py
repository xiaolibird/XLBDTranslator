# -*- coding: utf-8 -*-
"""札记库检索阈值的唯一集中地。

三条检索链路（notes_search CLI / 概念页证据召回 / digest 库内近邻注入）的相似度
阈值**有意不同**——各自的语料粒度与用途不同，且各有独立标定档案。此前它们散在
notes_search.py 的 argparse 默认值、topics.py 的模块常量、workflow.py 的函数签名
默认值三处，换 embedding 模型（roadmap 下一批：替换 bge-m3）时三处必须同步重标定，
签名默认值那处最容易漏。集中到这里后：换模型 → 重标定 → 只改本文件，调用处引用
常量不动。

铁律：这些是**标定值**，不是可随手调的偏好——每个常量的注释就是它的标定档案摘要，
改值必须先复跑对应标定（scripts/calibrate_*.py 或 docs/decisions/ 里的人工判定法），
并把新依据写回注释。不做 config/env 化，就是为了防止被环境变量静默覆盖。
"""

# ---------------------------------------------------------------------------
# notes_search.py CLI 的 --min-score 默认值（paper/highlight 混合检索，dense 侧过滤）
# ---------------------------------------------------------------------------
# 历史默认值，**无标定档案**——这是三个阈值里唯一没做过系统标定的（低门槛 + --limit
# 截断的组合在 CLI 交互场景够用；rag_bench 固化的是排序质量，不依赖这个门槛）。
# 若要标定，参考 docs/decisions/rag_bench_baseline_2026-08.md 的 case 集。
NOTES_SEARCH_MIN_SCORE = 0.4

# ---------------------------------------------------------------------------
# 概念页/问答 证据召回下限（句级 highlight 口径；topics.py / qa.py 共用）
# ---------------------------------------------------------------------------
# 召回相似度下限。**不要照抄 notes_search 的默认值（NOTES_SEARCH_MIN_SCORE=0.4，
# paper 级检索口径）**——粒度不同：这里过滤的是句级证据，阈值来自独立标定。
# 实测 query "shadow variable MNAR identification" 的最佳命中（chen2026Partial
# 「影子变量区间中点平均绝对误差 0.06」）只有 0.593 分，0.65（旧瘦库 paper 级口径，
# 已废弃）下整页召回 0 条。
#
# 2026-08-16 在本库 17775 条 highlight 上分段抽查的结果：
#   ≥0.55       全部题内，可直接当证据
#   0.50~0.55   一半题内一半漂移（"结局识别算法未做诊断性能评估"这类挂到因果泛化查询上）
#   <0.50       基本是词面巧合
# 故取 0.55。冷门概念（如影子变量）只召回十来条是**诚实的信号**而非故障——页面会把
# 证据数写在标题栏，缺口一节也会点明证据不足，这正是概念页该暴露的库覆盖缺口。
TOPICS_MIN_SIM = 0.55

# per-query 相对判据系数：eff_min = max(min_sim, alpha × 本次 query 的 top1 分)。
# 全局绝对阈值与查询强度耦合（2026-08-21 标定，config/topics.yaml 全部 36 条真实 query
# 实测，表存 docs/decisions/topics_threshold_calibration_2026-08.md）：强 query
# （top1≥0.70，如 "informative missingness"）在 0.55 下 top-200 全数过线，边缘尾巴
# 靠 per_query_k 截断而不是靠阈值；冷门 query（top1<0.62，如 "shadow variable MNAR"）
# 只召回个位数是诚实的库覆盖信号，不该再收紧。α=0.85 恰好只对 top1≥0.647 的强 query
# 生效（0.85×0.647≈0.55），对冷门 query 完全退回 floor：
#   α=0.80 几乎不生效（36 条里仅 4 条门槛动了）；α=0.90 把强 query 砍到只剩 3-7 条，
#   0.60~0.65 段的真命中被误杀。传 0 可彻底关闭相对判据（退回纯绝对阈值）。
TOPICS_RELATIVE_ALPHA = 0.85

# ---------------------------------------------------------------------------
# digest 库内近邻注入下限（paper+abstract 级向量，workflow._library_neighbors）
# ---------------------------------------------------------------------------
# 0.62 是 2026-08-21 摘要喂厚后的标定值（此前 0.65 是瘦库口径，已过时）：
# 30 条真实形状查询 × top-3 共 90 对逐对人工判定，≥0.62 注入精度 100%、
# 0.62-0.65 区间有 ~7/90 真近邻被旧值误杀；6 条硬离题探针（量子纠错/小麦施肥/
# 弱引力透镜等）max sim 0.575，与 0.62 有 4.5pt 安全边际。0.60-0.62 是弱相关与
# 离题的混杂区，留作缓冲勿再调低。定案依据是逐对人工判定档案
# docs/decisions/digest_neighbors_calibration_2026-08.md（方法二；裁决未落脚本，
# 不可脚本复现）。scripts/calibrate_digest_neighbors.py 实现的是同档案判失败的
# 方法一（topics 共现法，正负不可分），仅作分布监控用，复跑不会得出 0.62。
DIGEST_NEIGHBOR_MIN_SIM = 0.62
