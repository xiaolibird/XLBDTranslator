# -*- coding: utf-8 -*-
"""札记库检索阈值的唯一集中地。

四条检索链路（notes_search CLI / 概念页证据召回 / digest 库内近邻注入 / 问答 gap
回查）的相似度阈值**有意不同**——各自的语料粒度与用途不同，且各有独立标定档案。
此前它们散在 notes_search.py 的 argparse 默认值、topics.py 的模块常量、workflow.py
的函数签名默认值、qa.py 的模块常量四处，换 embedding 模型（roadmap 下一批：替换
bge-m3）时四处必须同步重标定，签名默认值与 qa.py 那两处最容易漏。集中到这里后：
换模型 → 重标定 → 只改本文件，调用处引用常量不动。

铁律：这些是**标定值**，不是可随手调的偏好——每个常量的注释就是它的标定档案摘要，
改值必须先复跑对应标定（scripts/calibrate_*.py 或 docs/decisions/ 里的人工判定法），
并把新依据写回注释。不做 config/env 化，就是为了防止被环境变量静默覆盖。

另：src/scholar/reranker.py 的 rerank 分是交叉编码器 logit，与本文件所有余弦门槛
**不可比**——只用于排序，任何门槛过滤都发生在重排之前（铁律见该模块 docstring）。
"""

# ---------------------------------------------------------------------------
# notes_search.py CLI 的 --min-score 默认值（paper/highlight 混合检索，dense 侧过滤）
# ---------------------------------------------------------------------------
# 历史默认值，**无标定档案**——这是三个阈值里唯一没做过系统标定的（低门槛 + --limit
# 截断的组合在 CLI 交互场景够用；rag_bench 固化的是排序质量，不依赖这个门槛）。
# 若要标定，参考 docs/decisions/rag_bench_baseline_2026-08.md 的 case 集。
#
# ⚠️ docs/skills/scholar-search/SKILL.md 的判重命令手传 `--min-score 0.62`，那是下面
# DIGEST_NEIGHBOR_MIN_SIM 的标定值，属**跨链路借用**而非本链路标定：掩码口径相同
# （paper+abstract），但 query 形状不同——skill 传的是标题或摘要句，digest 标定用的是
# title+abstract[:800]。这笔账 2026-08-23 复审时才被理清，此前无人记过。要把 0.62 固化成
# 本链路默认值，必须先按 digest_neighbors_calibration_2026-08.md 的方法二，在 skill 的
# 真实 query 形状上重做逐对人工判定。
NOTES_SEARCH_MIN_SCORE = 0.4

# ---------------------------------------------------------------------------
# 概念页/问答 证据召回下限（句级 highlight 口径；topics.py / qa.py 共用）
# ---------------------------------------------------------------------------
# 召回相似度下限。**不要照抄 notes_search 的默认值（NOTES_SEARCH_MIN_SCORE=0.4，
# paper 级检索口径）**——粒度不同：这里过滤的是句级证据，阈值来自独立标定。
# 实测 query "shadow variable MNAR identification" 的最佳命中（chen2026Partial
# 「影子变量区间中点平均绝对误差 0.06」）只有 0.593 分，0.65（旧瘦库 paper 级口径，
# 已废弃）下整页召回 0 条。
#
# 2026-08-16 在本库 17775 条 highlight 上分段抽查的结果：
#   ≥0.55       全部题内，可直接当证据
#   0.50~0.55   一半题内一半漂移（"结局识别算法未做诊断性能评估"这类挂到因果泛化查询上）
#   <0.50       基本是词面巧合
# 故取 0.55。冷门概念（如影子变量）只召回十来条是**诚实的信号**而非故障——页面会把
# 证据数写在标题栏，缺口一节也会点明证据不足，这正是概念页该暴露的库覆盖缺口。
TOPICS_MIN_SIM = 0.55

# per-query 相对判据系数：eff_min = max(min_sim, alpha × 本次 query 的 top1 分)。
# 全局绝对阈值与查询强度耦合（2026-08-21 标定，config/topics.yaml 全部 36 条真实 query
# 实测，表存 docs/decisions/topics_threshold_calibration_2026-08.md）：强 query
# （top1≥0.70，如 "informative missingness"）在 0.55 下 top-200 全数过线，边缘尾巴
# 靠 per_query_k 截断而不是靠阈值；冷门 query（top1<0.62，如 "shadow variable MNAR"）
# 只召回个位数是诚实的库覆盖信号，不该再收紧。α=0.85 恰好只对 top1≥0.647 的强 query
# 生效（0.85×0.647≈0.55），对冷门 query 完全退回 floor：
#   α=0.80 几乎不生效（36 条里仅 4 条门槛动了）；α=0.90 把强 query 砍到只剩 3-7 条，
#   0.60~0.65 段的真命中被误杀。传 0 可彻底关闭相对判据（退回纯绝对阈值）。
TOPICS_RELATIVE_ALPHA = 0.85

# ---------------------------------------------------------------------------
# digest 库内近邻注入下限（paper+abstract 级向量，workflow._library_neighbors）
# ---------------------------------------------------------------------------
# 0.62 是 2026-08-21 摘要喂厚后的标定值（此前 0.65 是瘦库口径，已过时）：
# 30 条真实形状查询 × top-3 共 90 对逐对人工判定，≥0.62 注入精度 100%、
# 0.62-0.65 区间有 ~7/90 真近邻被旧值误杀；6 条硬离题探针（量子纠错/小麦施肥/
# 弱引力透镜等）max sim 0.575，与 0.62 有 4.5pt 安全边际。0.60-0.62 是弱相关与
# 离题的混杂区，留作缓冲勿再调低。定案依据是逐对人工判定档案
# docs/decisions/digest_neighbors_calibration_2026-08.md（方法二；裁决未落脚本，
# 不可脚本复现）。scripts/calibrate_digest_neighbors.py 实现的是同档案判失败的
# 方法一（topics 共现法，正负不可分），仅作分布监控用，复跑不会得出 0.62。
DIGEST_NEIGHBOR_MIN_SIM = 0.62

# ---------------------------------------------------------------------------
# 问答 gap 回查 · 句级证据通道下限（qa.recheck_gaps）
# ---------------------------------------------------------------------------
# gap 回查有两条通道：概念页通道直接挂 TOPICS_MIN_SIM（见 qa.DEFAULT_GAP_TOPIC_MIN_SIM，
# 那条通道实测真假两档完全不重叠，本来就干净）；句级证据通道**必须比它高**，而且
# 必须配合脚手架剥离（`strip_gap_scaffold`）才成立。
#
# 首版与概念页通道共用 0.55，实测在"库里绝对没有"的 gap 上假阳性 **5/5**：
# 「AlphaFold 置信度校准」命中 0.651、「量子退火加速比」0.634、「中世纪欧洲农业史」
# 0.590、「NICU 喂养耐受性量表」0.673、「机器人抓取样本效率」0.675——
# 而真实 gap 的命中分是 0.699~0.728。**重叠，没有任何阈值能分开。**
# 这条防线存在的理由恰恰是"答错了还能核对，指错方向不会去核对"，
# 假阳性 5/5 等于用户按它去看 5 次白跑 5 次，比没有这条还坏。
#
# 剥掉否定脚手架之后重新标定（bge-m3，8 条真实 gap + 8 条构造成"库里绝对没有"的
# gap，全库 17775 条 highlight）：
#   真 gap 句级 top1： min 0.649  中位 0.695  max 0.753
#   假 gap 句级 top1： min 0.334  中位 0.575  max 0.641
#   阈值 0.55: 真 8/8 | 假 5/8
#   阈值 0.60: 真 8/8 | 假 3/8
#   阈值 0.65: 真 7/8 | 假 0/8      ← 取这个
#   阈值 0.69: 真 4/8 | 假 0/8
#   阈值 0.75: 真 1/8 | 假 0/8
# 两档的实测边界是 0.641/0.649，中间只有 0.008 宽；取 0.65 是**偏向精确率**的选择：
# 这一节的价值全在"它响的时候值得去看"，多漏一条真 gap 只是少一行提示，
# 多响一条假 gap 会把整条防线的可信度打掉。
#
# ⚠️ 与 NOTES_SEARCH 链路历史上出现过的 0.65 数值相同**纯属巧合**：那个是 paper 级
# 口径（标题+一句话），这个是 highlight 级 + 剥完脚手架的名词短语。不要因为
# "都是 0.65"就把两处并到一起。
#
# 2026-08-27 从 qa.py 的模块常量搬来（原 DEFAULT_GAP_EVIDENCE_MIN_SIM 字面量）：
# 标定档案本身一直是齐的，但值留在 qa.py 就绕开了本文件的铁律，换 embedding 时
# 扫不到。qa.py 侧保留同名别名以兼容既有引用。
QA_GAP_EVIDENCE_MIN_SIM = 0.65

# ---------------------------------------------------------------------------
# 证据充分性（拒答闸门，可信度加固 WO-4 / WO-4b 标定，WO-5 接线）
# ---------------------------------------------------------------------------
# 页面级闸门：召回到的独立来源（按 keeper 去重、撤稿不计）太少时不调 LLM，落一页
# 「库内证据不足」存根（`--force-synthesize` 可跳过）。两条链路用**不同判据**，原因如下。
#
# 标定档案：docs/decisions/evidence_sufficiency_calibration_2026-10-13.md（WO-4，固定阈值）
#           docs/decisions/evidence_sufficiency_distribution_2026-10-13.md（WO-4b，分布判据）
# 样本：正例 20（9 概念页 + 6 已归档问答 + **5 道代拟冷门题**）、反例 13（含 3 道平凡反例）。
#
# 摘要（诚实版）：
#   * 分布判据**没有显著优于**固定阈值：样本内漏拒 1/13 对 3/13，但留一检验两者都漏拒 3/13
#     （误拒都是 0），样本内那点优势不能外推。三道难例（机器人抓取、影像分割数据增强、
#     糖尿病视网膜病变筛查）两种判据都分不开——它们在库里有真实的 ML/影像方法学近邻，
#     相似度本身不区分「相邻但画像外」。真正兜底的是页面顶部的覆盖范围说明，不是闸门。
#   * 5 道冷门正例是**代拟的**，用户尚未替换；这组样本决定了余量（Rubin 1976 一类题恰好卡线），
#     替换后须复跑标定再回头核对下面的取值。
#   * 换 embedding 模型后必须重标：
#       python scripts/calibrate_evidence_sufficiency.py --mode distribution --notes-dir <新快照>
#       python scripts/calibrate_evidence_sufficiency.py --mode fixed        --notes-dir <新快照>
#     floor 与固定下限与模型的余弦分布绑定，必须重标；e 不必（z* 随背景规模 N 自动变）。

# --- 问答页：分布判据（coverage.dynamic_sufficiency，基于全库扫描，不经召回截断）---
# 动态阈值 T = max(EVIDENCE_DYNAMIC_FLOOR, mean + z*·std)，z* = Φ⁻¹(1 − e/N)；
# 独立来源数 = 全库扫描里最高分 ≥ T 的 keeper 数，< QA_MIN_INDEPENDENT_SOURCES 即拒答。
# 0.58 是绝对下限：冷门问题（Rubin 1976、影子变量，背景均值约 0.35）上真正起作用的就是它。
EVIDENCE_DYNAMIC_FLOOR = 0.58
# e：N 个背景点里期望只有 e 个靠偶然越过阈值（e=1、N≈3.7 万时 z*≈4.04）。名义值，非显著性水平。
EVIDENCE_DYNAMIC_EXPECTED_CHANCE = 1.0
# m=2：WO-4b 的「稳」档（正例余量 1，漏拒 3/13，与固定阈值持平）。激进档 m=3 漏拒 1/13，
# 但 4 个正例恰好卡线（余量 0），一道更冷的真实问题就会误拒；Q8「宁可回避不足也不误拒」。
QA_MIN_INDEPENDENT_SOURCES = 2
# 问答 answer 级判据：points 引用的独立来源合计不足此数，answer 前加「库内证据不足」提示行。
# **未标定**（需要真实合成出的 points，无 LLM 无法评估）；已归档 6 页「依据」篇数 5~14，均不触发。
QA_ANSWER_MIN_SOURCES = 2

# --- 概念页：固定判据（WO-4，按召回后的证据列表计数）---
# WO-4b 实测概念页背景高（均值 0.46~0.48），动态阈值会被抬到 0.63~0.69，部分页来源数只剩
# 3 篇（adversarial-evidence），余量远小于固定判据（9 页在 0.55 下每页 ≥ 45 篇，k=3 余量 41），
# 所以概念页**不接动态判据**。下限取 TOPICS_MIN_SIM 同值 0.55（召回本身的门槛，概念页的
# 所有证据都已 ≥ 它；这里单列常量，是为了日后召回门槛变动不会悄悄改掉拒答口径）。
EVIDENCE_SUFFICIENCY_MIN_SIM = 0.55
TOPIC_MIN_INDEPENDENT_SOURCES = 3

# ---------------------------------------------------------------------------
# 入库确认弹窗（可信度加固 WO-8a，设计 §12.1；用户 2026-10-21 拍板）
# ---------------------------------------------------------------------------
# 这些是**产品口径**而非标定值：决定弹窗里列哪些条目、一页多长。无标定档案。
# 置信度 ≤ 此值的 EXCLUDE 进弹窗（默认不勾）；> 此值的高置信 EXCLUDE 只随机抽查。
# 0.85 取自设计 §12 拍板表原话；基线评测里 EXCLUDE 的置信度分段见 filter_eval.conf_bin。
CONFIRM_LOWCONF_MAX = 0.85
# 高置信 EXCLUDE 的随机抽查条数（每个 digest run 一次，闭区间）：条数随池子大小在区间内取，
# 池子 < 下限时全取。种子 = run_id，同一 run 重复建队列得到同一批，可复现。
CONFIRM_AUDIT_MIN = 3
CONFIRM_AUDIT_MAX = 5
CONFIRM_AUDIT_POOL_PER_EXTRA = 40      # 池每多这么多条，抽查多 1 条（封顶 CONFIRM_AUDIT_MAX）
# choose from list 一页最多条目数（再多滚动难看、也容易误勾）；标题截断字数
CONFIRM_PAGE_SIZE = 40
CONFIRM_TITLE_CHARS = 110
# 开场询问框 giving up after（秒）：到点视为无人应答 → 本轮挂起；列表页给更长的硬超时
CONFIRM_ASK_TIMEOUT_S = 600
CONFIRM_PAGE_TIMEOUT_S = 1800
# 摘要速览 md 里每篇摘要保留字数（设计 §12.1「摘要前 400 字」）
CONFIRM_SUMMARY_CHARS = 400
# 队列只扫最近这么多天内的 digest run（更早的不再自动入队，须手动指定窗口）
CONFIRM_QUEUE_LOOKBACK_DAYS = 28

# ---------------------------------------------------------------------------
# 持续评测 S-stream 层（WO-8b，设计 §12.2）
# ---------------------------------------------------------------------------
# 确认标签并入金标准时只取最近这么多周（按 confirmed_at 滚动）；研究兴趣在漂移，旧标签会过时。
STREAM_WINDOW_WEEKS = 12

# ---------------------------------------------------------------------------
# 月度画像漂移提醒（WO-8c，设计 §12.3）
# ---------------------------------------------------------------------------
# 「成簇」判据：同一原因/语义簇 ≥ 此篇数，且占该类分歧（全部补勾 / 全部取消）≥ 此比例。
# 初值取设计拍板表：5 篇且占 ≥ 50%；跑几个月后按误报/漏报复核，改值须写回依据。
DRIFT_MIN_CLUSTER = 5
DRIFT_MIN_SHARE = 0.5
# 回看窗口（周）。设计原文「近 4 周」
DRIFT_LOOKBACK_WEEKS = 4
# 补勾论文按向量做语义聚类的单链接相似度。**借用** DIGEST_NEIGHBOR_MIN_SIM 的口径
# （同为 标题+摘要 级向量），未针对「同主题簇」单独标定；偏高 = 簇更碎、更保守（不易误报）。
DRIFT_CLUSTER_MIN_SIM = DIGEST_NEIGHBOR_MIN_SIM
